local cfgy = require("cfgy")
local cfg = cfgy.load(arg[1])
assert(cfg.wide == 9007199254740993 and math.type(cfg.wide) == "integer")
assert(cfg.label == "café 雪 😀" and cfg.group["a.b"] == 7)
assert(cfg.mixed[1] == cfgy.null and cfg.mixed[2] and #cfg.mixed == 7)
assert(getmetatable(cfg.mixed[7]).__name == "cfgy.list")
assert(cfg.absolute[2] == 2.5)
local ok, err = pcall(cfgy.loads, "x: sqrt(-1)")
assert(not ok and err:find("<string>:1:4:", 1, true))
